// Generates src/icons.generated.ts from the Bootstrap Icons the web app uses,
// so the mobile app shows the exact same SVG glyphs.
// Run: npm run icons
const fs = require("fs");
const path = require("path");

const NAMES = [
  "search", "arrow-right", "arrow-left", "geo-alt", "geo-alt-fill", "shield-check", "shield-lock",
  "house", "house-heart", "house-heart-fill", "houses", "house-add", "house-x", "house-check",
  "heart", "heart-fill", "envelope", "info-circle", "send", "person", "person-fill", "person-plus",
  "check-circle", "check-circle-fill", "telephone", "box-seam", "plus-circle", "door-open",
  "currency-rupee", "cup-hot", "people", "images", "eye", "eye-slash", "lock", "x-circle",
  "trash3", "pencil-square", "clock", "sliders", "speedometer2", "cash-stack", "person-vcard",
  "calendar3", "wifi-off", "box-arrow-right", "x-lg", "check2", "patch-check-fill", "grid",
  "chat-left-text", "list", "cloud-arrow-up", "camera", "file-earmark-pdf", "exclamation-circle",
];

const dir = path.join(__dirname, "..", "node_modules", "bootstrap-icons", "icons");
const out = {};
for (const name of NAMES) {
  const svg = fs.readFileSync(path.join(dir, `${name}.svg`), "utf8");
  out[name] = [...svg.matchAll(/<path\b([^>]*?)\/>/g)].map((m) => ({
    d: /\bd="([^"]+)"/.exec(m[1])[1],
    evenodd: /fill-rule="evenodd"/.test(m[1]),
  }));
}

const body =
  "// AUTO-GENERATED by scripts/build-icons.js from bootstrap-icons. Do not edit.\n" +
  "export type IconPath = { d: string; evenodd: boolean };\n" +
  `export const ICON_PATHS: Record<string, IconPath[]> = ${JSON.stringify(out, null, 1)};\n` +
  `export type IconName = ${NAMES.map((n) => JSON.stringify(n)).join(" | ")};\n`;
fs.writeFileSync(path.join(__dirname, "..", "src", "icons.generated.ts"), body);
console.log(`Wrote ${NAMES.length} icons`);
